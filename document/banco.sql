# Criação da tabela no Oracle para armazenar os dados da colheita
CREATE TABLE TAB_COLHEITA_CANA (
    ID_TALHAO NUMBER PRIMARY KEY,
    TIPO_COLHEITA VARCHAR2(20) NOT NULL,
    PROD_ESPERADA NUMBER(10,2) NOT NULL,
    PROD_REAL NUMBER(10,2) NOT NULL,
    PERDA_PERC NUMBER(5,2) NOT NULL,
    STATUS VARCHAR2(30) NOT NULL
);
